out = []
out.append('#include "gfx.h"')
out.append("")
out.append("const u8 font8x8[96][8] = {")
for c in chars:
    rows = G[c]
    vals = []
    for r in rows:
        v = 0
        for col in range(8):
            if r[col] == '#':
                v |= (1 << (7 - col))
        vals.append(f"0x{v:02X}")
    esc = c
    name = {" ": '" "', "\\": "'\\\\'", "'": "\\'"}.get(c, None)
    label = f"'{name}'" if name else f"'{esc}'"
    out.append(f"    /* {label} */ {{{', '.join(vals)}}},")
out.append("};")

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")

